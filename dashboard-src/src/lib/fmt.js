/* ============================================================================
   ПІДПИСИ КОШИКІВ ЧАСУ

   ЩО БУЛО НЕ ТАК. Тижневий кошик підписувався ОДНІЄЮ датою — його початком.
   Читач бачив «07-13» і не знав, це день чи тиждень; а на щільній осі сусідні
   підписи ще й зливалися в суцільну смугу («07-1407-1507-16»). Обидві вади
   від одного: підпис не казав, який відрізок він позначає.

   Тепер тижневий кошик підписується діапазоном «13.07–19.07», а денний —
   короткою датою. Довший підпис вимагає більше місця, тому осі з тижнями
   отримують поворот або фасети — залежно від графіка.
   ============================================================================ */

const pad = (n) => String(n).padStart(2, "0");

export function weekEnd(startISO) {
  const d = new Date(startISO + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() + 6);
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`;
}

const short = (iso) => `${iso.slice(8, 10)}.${iso.slice(5, 7)}`;

/** Підпис кошика: діапазон для тижня, коротка дата для дня. */
export function bucketLabel(iso, step) {
  if (step !== "week") return short(iso);
  return `${short(iso)}–${short(weekEnd(iso))}`;
}

/** Повний підпис для підказки — з роком, бо в тексті звіту він потрібен. */
export function bucketFull(iso, step) {
  return step === "week" ? `${iso} — ${weekEnd(iso)}` : iso;
}
